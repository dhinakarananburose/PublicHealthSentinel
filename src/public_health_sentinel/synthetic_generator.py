"""Deterministic synthetic data generator for public health surveillance and mobility indicators.

Generates realistic benchmark datasets for testing anomaly detection and data pipelines:
- Configurable duration (default: 180 days)
- Standard regions: REGION_A through REGION_E
- Standard syndromes: Respiratory, Gastrointestinal, Febrile
- Realistic counts with Poisson noise, weekday reporting patterns, and seasonal drift
- Injected synthetic spikes with exact provenance tracking
- Aggregated mobility metrics with documented units
- Configurable observation date omissions (distinguishable from zero counts)

SCIENTIFIC DISCLAIMER:
All generated observations are synthetic simulations (data_status="simulated").
They do not represent genuine patient health records or real-world clinical evidence.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
from datetime import date, datetime, timedelta, timezone
from pathlib import Path
from typing import Any, Sequence

import numpy as np
import pandas as pd

from public_health_sentinel.schemas import (
    AggregatedObservation,
    DataStatus,
    MobilityIndicator,
)

DEFAULT_REGIONS: tuple[str, ...] = (
    "REGION_A",
    "REGION_B",
    "REGION_C",
    "REGION_D",
    "REGION_E",
)

DEFAULT_SYNDROMES: tuple[str, ...] = (
    "Respiratory",
    "Gastrointestinal",
    "Febrile",
)

# Reference population sizes per region (used as denominators)
DEFAULT_POPULATIONS: dict[str, int] = {
    "REGION_A": 250_000,
    "REGION_B": 500_000,
    "REGION_C": 150_000,
    "REGION_D": 750_000,
    "REGION_E": 350_000,
}

# Baseline facility counts per region
DEFAULT_FACILITIES: dict[str, int] = {
    "REGION_A": 8,
    "REGION_B": 15,
    "REGION_C": 5,
    "REGION_D": 22,
    "REGION_E": 11,
}

# Base incidence rates per 100,000 population per day
BASELINE_INCIDENCE_PER_100K: dict[str, float] = {
    "Respiratory": 28.0,
    "Gastrointestinal": 12.0,
    "Febrile": 18.0,
}

# Day-of-week reporting factors (0=Monday, ..., 6=Sunday)
# Reflects clinical reporting backlogs on Monday and lower reporting on weekends
WEEKDAY_REPORTING_FACTORS: tuple[float, ...] = (
    1.25,  # Mon
    1.10,  # Tue
    1.02,  # Wed
    0.98,  # Thu
    0.95,  # Fri
    0.82,  # Sat
    0.88,  # Sun
)

MOBILITY_METRICS: tuple[dict[str, str], ...] = (
    {
        "metric": "transit_station_pct_change",
        "description": "Percentage change in visitors to public transit hubs relative to baseline.",
        "unit": "percentage_deviation",
    },
    {
        "metric": "workplace_pct_change",
        "description": "Percentage change in workplace presence relative to baseline.",
        "unit": "percentage_deviation",
    },
    {
        "metric": "residential_pct_change",
        "description": "Percentage change in time spent in residential locations relative to baseline.",
        "unit": "percentage_deviation",
    },
)


@dataclass(frozen=True)
class InjectedSpike:
    """Metadata describing a deliberately injected synthetic anomaly spike."""

    observation_date: date
    region_id: str
    syndrome: str
    spike_count: int
    duration_days: int = 1
    description: str = "Injected syndromic surge"

    def to_dict(self) -> dict[str, Any]:
        """Convert spike metadata to serializable dictionary."""
        return {
            "observation_date": self.observation_date.isoformat(),
            "region_id": self.region_id,
            "syndrome": self.syndrome,
            "spike_count": self.spike_count,
            "duration_days": self.duration_days,
            "description": self.description,
        }


@dataclass
class SyntheticDataset:
    """Container for synthetic surveillance and mobility data generated by a run."""

    surveillance: list[AggregatedObservation]
    mobility: list[MobilityIndicator]
    injected_spikes: list[InjectedSpike]
    metadata: dict[str, Any] = field(default_factory=dict)

    def to_surveillance_df(self) -> pd.DataFrame:
        """Convert surveillance observations to a pandas DataFrame."""
        rows = [obs.model_dump() for obs in self.surveillance]
        df = pd.DataFrame(rows)
        if not df.empty:
            df["observation_date"] = pd.to_datetime(df["observation_date"]).dt.date
        return df

    def to_mobility_df(self) -> pd.DataFrame:
        """Convert mobility indicators to a pandas DataFrame."""
        rows = [ind.model_dump() for ind in self.mobility]
        df = pd.DataFrame(rows)
        if not df.empty:
            df["observation_date"] = pd.to_datetime(df["observation_date"]).dt.date
        return df

    def save_csv(
        self,
        surveillance_path: Path | str,
        mobility_path: Path | str,
        spikes_path: Path | str | None = None,
    ) -> None:
        """Save synthetic datasets to CSV files with parent directory creation."""
        s_path = Path(surveillance_path)
        m_path = Path(mobility_path)
        s_path.parent.mkdir(parents=True, exist_ok=True)
        m_path.parent.mkdir(parents=True, exist_ok=True)

        self.to_surveillance_df().to_csv(s_path, index=False)
        self.to_mobility_df().to_csv(m_path, index=False)

        if spikes_path:
            sp_path = Path(spikes_path)
            sp_path.parent.mkdir(parents=True, exist_ok=True)
            spikes_df = pd.DataFrame([s.to_dict() for s in self.injected_spikes])
            spikes_df.to_csv(sp_path, index=False)


def generate_synthetic_data(
    start_date: date = date(2026, 1, 1),
    duration_days: int = 180,
    regions: Sequence[str] = DEFAULT_REGIONS,
    syndromes: Sequence[str] = DEFAULT_SYNDROMES,
    seed: int = 42,
    inject_spikes: bool = True,
    custom_spikes: Sequence[InjectedSpike] | None = None,
    missing_dates_fraction: float = 0.0,
    missing_facility_count_fraction: float = 0.05,
    missing_denominator_fraction: float = 0.05,
    data_source: str = "SYNTHETIC_GENERATOR",
) -> SyntheticDataset:
    """Generate deterministic synthetic surveillance and mobility datasets.

    Args:
        start_date: Calendar start date.
        duration_days: Total span in days (default: 180).
        regions: List of region IDs to generate data for.
        syndromes: List of syndromes to simulate.
        seed: Random seed for deterministic reproducibility.
        inject_spikes: Whether to inject known anomalous spikes.
        custom_spikes: Optional explicit list of spikes. If None and inject_spikes=True,
            default benchmark spikes are injected.
        missing_dates_fraction: Fraction of (date, region, syndrome) combinations
            deliberately omitted from the dataset (distinguishable from 0 counts).
        missing_facility_count_fraction: Fraction of records with facility count = None.
        missing_denominator_fraction: Fraction of records with population denominator = None.
        data_source: Provenance stream identifier.

    Returns:
        SyntheticDataset containing validated Pydantic models and spike provenance.
    """
    rng = np.random.default_rng(seed)
    ingestion_ts = datetime.now(timezone.utc)

    # 1. Determine planned spike events
    spikes: list[InjectedSpike] = []
    if inject_spikes:
        if custom_spikes is not None:
            spikes.extend(custom_spikes)
        else:
            # Deterministic default benchmark spikes
            spikes.extend(
                [
                    InjectedSpike(
                        observation_date=start_date + timedelta(days=45),
                        region_id="REGION_A",
                        syndrome="Respiratory",
                        spike_count=95,
                        duration_days=3,
                        description="Mid-season localized respiratory surge",
                    ),
                    InjectedSpike(
                        observation_date=start_date + timedelta(days=90),
                        region_id="REGION_C",
                        syndrome="Gastrointestinal",
                        spike_count=60,
                        duration_days=2,
                        description="Food/water-borne gastrointestinal cluster",
                    ),
                    InjectedSpike(
                        observation_date=start_date + timedelta(days=130),
                        region_id="REGION_B",
                        syndrome="Febrile",
                        spike_count=120,
                        duration_days=4,
                        description="Multi-day unexplained febrile cluster",
                    ),
                ]
            )

    # Build spike lookup: (date, region_id, syndrome) -> additional count
    spike_map: dict[tuple[date, str, str], int] = {}
    for s in spikes:
        for offset in range(s.duration_days):
            target_dt = s.observation_date + timedelta(days=offset)
            key = (target_dt, s.region_id, s.syndrome)
            # Additive if multiple spikes coincide
            spike_map[key] = spike_map.get(key, 0) + s.spike_count

    # 2. Generate daily surveillance observations
    surveillance_records: list[AggregatedObservation] = []

    for day_idx in range(duration_days):
        current_date = start_date + timedelta(days=day_idx)
        weekday = current_date.weekday()
        weekday_factor = WEEKDAY_REPORTING_FACTORS[weekday]

        # Slow seasonal macro wave (180-day half-cycle)
        seasonal_factor = 1.0 + 0.15 * np.sin(np.pi * (day_idx / max(duration_days, 1)))

        for region_id in regions:
            pop = DEFAULT_POPULATIONS.get(region_id, 300_000)
            facility_base = DEFAULT_FACILITIES.get(region_id, 10)

            for syndrome in syndromes:
                # Deliberate missingness check (omitting rows completely)
                if missing_dates_fraction > 0 and rng.uniform(0.0, 1.0) < missing_dates_fraction:
                    continue

                base_rate = BASELINE_INCIDENCE_PER_100K.get(syndrome, 20.0)
                expected_count = (pop / 100_000.0) * base_rate * weekday_factor * seasonal_factor

                # Sample Poisson background variation
                baseline_sample = int(rng.poisson(lam=max(expected_count, 1.0)))

                # Add injected spike if present
                injected_addition = spike_map.get((current_date, region_id, syndrome), 0)
                final_count = max(0, baseline_sample + injected_addition)

                # Optional facility count with missingness
                if rng.uniform(0.0, 1.0) < missing_facility_count_fraction:
                    reporting_facility_count = None
                else:
                    reporting_facility_count = max(1, int(facility_base + rng.integers(-2, 3)))

                # Optional denominator with missingness
                if rng.uniform(0.0, 1.0) < missing_denominator_fraction:
                    population_denominator = None
                else:
                    population_denominator = pop

                obs = AggregatedObservation(
                    observation_date=current_date,
                    region_id=region_id,
                    syndrome=syndrome,
                    report_count=final_count,
                    reporting_facility_count=reporting_facility_count,
                    population_denominator=population_denominator,
                    data_source=data_source,
                    data_status=DataStatus.SIMULATED,
                    ingestion_timestamp=ingestion_ts,
                )
                surveillance_records.append(obs)

    # 3. Generate daily mobility indicators
    mobility_records: list[MobilityIndicator] = []

    for day_idx in range(duration_days):
        current_date = start_date + timedelta(days=day_idx)
        weekday = current_date.weekday()
        is_weekend = weekday >= 5

        for region_id in regions:
            for metric_info in MOBILITY_METRICS:
                metric_name = metric_info["metric"]

                # Construct realistic synthetic signal
                if metric_name == "transit_station_pct_change":
                    base_val = -15.0 if not is_weekend else -35.0
                    noise = rng.normal(0.0, 4.0)
                elif metric_name == "workplace_pct_change":
                    base_val = -8.0 if not is_weekend else -65.0
                    noise = rng.normal(0.0, 3.5)
                elif metric_name == "residential_pct_change":
                    base_val = 6.0 if not is_weekend else 18.0
                    noise = rng.normal(0.0, 2.0)
                else:
                    base_val = 0.0
                    noise = rng.normal(0.0, 5.0)

                # Long-term drift over 180 days
                drift = 5.0 * np.sin(2 * np.pi * (day_idx / duration_days))
                val = round(float(base_val + drift + noise), 2)

                ind = MobilityIndicator(
                    observation_date=current_date,
                    region_id=region_id,
                    mobility_metric=metric_name,
                    mobility_value=val,
                    data_source="SYNTHETIC_MOBILITY_GENERATOR",
                    data_status=DataStatus.SIMULATED,
                    ingestion_timestamp=ingestion_ts,
                )
                mobility_records.append(ind)

    metadata: dict[str, Any] = {
        "generator": "public_health_sentinel.synthetic_generator",
        "seed": seed,
        "start_date": start_date.isoformat(),
        "duration_days": duration_days,
        "regions": list(regions),
        "syndromes": list(syndromes),
        "surveillance_records_generated": len(surveillance_records),
        "mobility_records_generated": len(mobility_records),
        "injected_spikes_count": len(spikes),
        "missing_dates_fraction": missing_dates_fraction,
        "provenance_disclaimer": "All records are simulated synthetic benchmarks (data_status='simulated'). Never use as real-world evidence.",
    }

    return SyntheticDataset(
        surveillance=surveillance_records,
        mobility=mobility_records,
        injected_spikes=spikes,
        metadata=metadata,
    )
