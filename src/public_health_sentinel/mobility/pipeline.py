            "",
            "| Evaluation Metric | Model A: Surveillance-Only | Model B: Surveillance + Mobility | Absolute Difference (B - A) |",
            "| :--- | :--- | :--- | :--- |",
            f"| **F1-Score** | **`{base.f1_score:.4f}`** | **`{aug.f1_score:.4f}`** | **`{comparison.delta_f1:+.4f}`** |",
            f"| **Precision** | `{base.precision:.4f}` | `{aug.precision:.4f}` | `{comparison.delta_precision:+.4f}` |",
